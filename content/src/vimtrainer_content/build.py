"""The content build: sources -> windows -> drafts -> Neovim oracle -> gates -> build/.

``build()`` regenerates the output directory from scratch:

    build/
      exercises/<lang>/<skill>/<id>.json
      index.json                 # per lang, per skill: ids, count, parMedian, thin
      stats/node_frequency.json  # named nodes per 100 lines over the whole corpus
      stats/gates.json           # rejections per gate, skill and template
      supported_commands.md
      ATTRIBUTION.md

Drafts are verified in rounds. Each round takes, per skill, enough of the next drafts
(round-robin across templates, so one template cannot crowd out the others) to fill the
remaining quota, and replays every candidate of every draft in parallel batch nvim
processes. Rounds stop when every skill has ``cap`` exercises or runs out of drafts.
"""

from __future__ import annotations

import collections
import concurrent.futures
import datetime
import itertools
import json
import os
import pathlib
import re
import shutil
import statistics
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from typing import Any, Final

from vimtrainer_content import gates, oracle, par_search, snippets, sources, templates
from vimtrainer_content.lang import Language
from vimtrainer_content.lang.python import LANG as PYTHON

REPO_ROOT: Final = sources.CONTENT_DIR.parent
DEFAULT_OUT: Final = REPO_ROOT / "build"
REVIEWED_TXT: Final = sources.CONTENT_DIR / "reviewed.txt"
REJECTED_TXT: Final = sources.CONTENT_DIR / "rejected.txt"
TARGET_SKILLS: Final = (
    "m.find", "m.rel", "m.match", "o.delete", "o.change", "o.indent", "o.case", "t.quote", "t.paren",
    "t.bracket", "t.brace", "t.word", "x.subst", "x.copymove", "n.unmatched",
)
LANGS: Final = {"python": PYTHON}
DEFAULT_CAP: Final = 40
JOBS_PER_PROCESS: Final = 400
JOB_TIMEOUT_S: Final = 3.0
PROBE_JOBS_PER_PROCESS: Final = 10  # cursor drafts per nvim; each replays ~1500 probe motions
PROVENANCE: Final = "generated by vimtrainer-content templates from real source code; pars verified in Neovim; no LLM"
# Emulator support per skill, copied from 02-skill-graph.md until the emulator oracle exists.
EMULATOR: Final = collections.defaultdict(
    lambda: {"vscodevim": "full", "ideavim": "full", "web": "unverified"},
    {"m.match": {"vscodevim": "partial", "ideavim": "full", "web": "unverified"}},
)


@dataclass
class Report:
    """What a build produced and rejected."""

    counts: dict[str, dict[str, int]] = field(default_factory=dict)  # lang -> skill -> count
    rejections: collections.Counter = field(default_factory=collections.Counter)  # (gate, skill, template)
    windows: int = 0
    drafts: int = 0
    replays: int = 0

    def thin(self) -> dict[str, list[str]]:
        """(lang -> skills) below the per-skill minimum."""
        return {lang: [s for s, n in skills.items() if gates.is_thin(n)] for lang, skills in self.counts.items()}


# Public Functions =================================================================================


def build(
    out: pathlib.Path = DEFAULT_OUT, cap: int = DEFAULT_CAP, workers: int | None = None,
    skills: Sequence[str] = TARGET_SKILLS, offline: bool = False, log=print,
    sources_toml: pathlib.Path = sources.SOURCES_TOML,
) -> Report:
    """Regenerate ``out`` from the sources in sources.toml. See the module docstring."""
    _check_out_dir(out)
    report = Report()
    workers = workers or os.cpu_count() or 4
    stamp = oracle.verified_stamp()
    reviewed, rejected = _read_ids(REVIEWED_TXT), _read_ids(REJECTED_TXT)
    used_sources: list[tuple[sources.Source, str, str]] = []
    exercises: list[dict[str, Any]] = []
    frequencies: dict[str, Any] = {}

    for lang_name, lang in LANGS.items():
        srcs = [s for s in sources.load_sources(sources_toml) if s.lang == lang_name]
        windows, texts = [], []
        for src in srcs:
            if src.local is None and (not offline or not src.path.exists()):
                log(f"fetch {src.repo}@{src.commit[:12]}")
                sources.fetch(src)
            copyright_line = sources.verify_license(src)
            used_sources.append((src, copyright_line, sources.license_text(src)))
            for rel, text in sources.snippet_files(src):
                texts.append(text)
                for win in snippets.windows(text, src.meta(rel)):
                    found = snippets.secret_findings(win.lines)
                    if found:
                        report.rejections[("secret", "-", "-")] += 1
                        continue
                    windows.append(win)
        frequencies[lang_name] = _frequency(texts, lang)
        report.windows += len(windows)
        drafts = [d for w in windows for d in templates.generate(w, lang) if d.skill in skills]
        report.drafts += len(drafts)
        log(f"{lang_name}: {len(texts)} files, {len(windows)} windows, {len(drafts)} drafts")
        accepted = _verify_rounds(drafts, lang, cap, workers, stamp, rejected, report, log)
        for ex in accepted:
            ex["reviewed"] = ex["id"] in reviewed
        exercises.extend(accepted)
        report.counts[lang_name] = {s: sum(e["skill"] == s for e in accepted) for s in skills}

    _write(out, exercises, report, used_sources, frequencies, stamp)
    return report


def candidate_keys(draft: templates.Draft, exercise: dict[str, Any]) -> list[str]:
    """Every key string replayed for a draft: variants, alternates, idioms, shortcuts."""
    seeds = par_search.candidates(exercise)
    return list(dict.fromkeys(itertools.chain(draft.variants, seeds, draft.idioms, draft.forbid)))


def evaluate(
    draft: templates.Draft, lang: Language, verdicts: dict[str, oracle.Verdict], stamp: str,
    probes: Sequence[list[int] | None] | None = None,
) -> tuple[dict[str, Any] | None, str, str]:
    """Apply gates 3-6 to a verified draft.

    ``probes`` are where each of ``gates.cursor_probes`` landed (cursor drafts only);
    without them the cursor-probe part of gate 4 is skipped.

    Returns
    -------
    tuple
        ``(exercise or None, gate name, detail)``; gate is ``"ok"`` on acceptance.
    """
    margin = 0 if draft.kind == oracle.Kind.CURSOR else gates.FLAG_MARGIN
    canonical, best, problem = gates.judge_par(draft.variants, verdicts, draft.forbid, margin)
    if canonical is None:
        return None, "oracle", problem or ""
    if problem:
        return None, "shortcut" if problem.startswith("shortcut") else "par", problem
    ex = draft.exercise(lang.name)
    if draft.kind == oracle.Kind.CURSOR and probes is not None:
        # Ties are allowed for the declared solutions only: the idiom lists hold plain
        # motions ($, w, W) precisely so that they are caught here.
        allowed = {*draft.variants, *draft.alternates}
        problem = gates.cursor_probe_problem(ex, canonical.count, gates.cursor_probes(ex), probes, allowed)
        if problem:
            return None, "motion", problem
    problem = gates.anti_shortcut_problem(ex, canonical.count, draft.typed)
    if problem:
        return None, "anti-shortcut", problem
    problem = gates.target_problem(ex, draft.target, draft.task)
    if problem:
        return None, "target", problem
    known = [*draft.variants, *draft.alternates]
    alternates = [k for k in dict.fromkeys(known) if k != canonical.keys and verdicts[k].passed]
    par = {"keys": canonical.keys, "count": canonical.count, "verified": stamp}
    if best is not None and best.count < canonical.count:
        par["best"] = {"keys": best.keys, "count": best.count}
    win = draft.window
    source = dict(win.source, lines=[win.first_line, win.last_line])
    if "lines" in ex["expect"]:
        ex["expect"]["lines"] = [ln.rstrip() for ln in ex["expect"]["lines"]]
    exercise = {
        "id": f"{lang.short}/{draft.skill}/{draft.uid}",
        "skill": draft.skill, "lang": lang.name, "kind": draft.kind, "task": draft.task,
        "start": ex["start"], "expect": ex["expect"], "par": par, "alternates": alternates,
        "hints": [h for h in draft.hints if not h["trigger"] or not re.search(h["trigger"], canonical.keys)],
        "tags": draft.tags, "target": draft.target, "template": draft.template,
        "source": source, "emulator": dict(EMULATOR[draft.skill]), "params": draft.params,
        "provenance": PROVENANCE, "naive": gates.naive_cost(ex),
    }
    return exercise, "ok", ""


# Private Functions ================================================================================


def _check_out_dir(out: pathlib.Path):
    if out.exists() and not (out.name == "build" or (out / "index.json").exists() or not any(out.iterdir())):
        raise RuntimeError(f"refusing to wipe {out}: not a build directory")


def _read_ids(path: pathlib.Path) -> set[str]:
    if not path.exists():
        return set()
    return {ln.split("#")[0].strip() for ln in path.read_text().splitlines() if ln.split("#")[0].strip()}


def _frequency(texts: list[str], lang: Language) -> dict[str, Any]:
    freq = snippets.node_frequency(texts)
    freq["mapped"] = {t: freq["per100Lines"].get(t, 0.0) for t in sorted(lang.nodes)}
    return freq


def _schedule(drafts: Sequence[templates.Draft]) -> dict[str, collections.deque]:
    """Per skill, a queue of drafts round-robin across templates, each template in uid order."""
    by_skill: dict[str, dict[str, list[templates.Draft]]] = collections.defaultdict(lambda: collections.defaultdict(list))
    for d in drafts:
        by_skill[d.skill][d.template].append(d)
    queues = {}
    for skill, per_template in by_skill.items():
        lists = [sorted(v, key=lambda d: d.uid) for _, v in sorted(per_template.items())]
        merged = [d for group in itertools.zip_longest(*lists) for d in group if d is not None]
        queues[skill] = collections.deque(merged)
    return queues


def _verify_rounds(
    drafts: Sequence[templates.Draft], lang: Language, cap: int, workers: int, stamp: str,
    rejected_ids: set[str], report: Report, log,
) -> list[dict[str, Any]]:
    queues = _schedule(drafts)
    accepted: dict[str, list[dict[str, Any]]] = collections.defaultdict(list)
    round_no = 0
    while True:
        batch = []
        for skill, queue in queues.items():
            need = cap - len(accepted[skill])
            take = min(len(queue), max(need * 2, 0) + (4 if need > 0 else 0))
            batch.extend(queue.popleft() for _ in range(take))
        if not batch:
            break
        round_no += 1
        verdicts = _replay(batch, lang, workers, report)
        probes = _probe(batch, lang, workers)
        for draft in batch:
            if len(accepted[draft.skill]) >= cap:
                continue
            ex, gate, detail = evaluate(draft, lang, verdicts[id(draft)], stamp, probes.get(id(draft)))
            if ex is not None and ex["id"] in rejected_ids:
                ex, gate = None, "human-rejected"
            if ex is None:
                report.rejections[(gate, draft.skill, draft.template)] += 1
                continue
            accepted[draft.skill].append(ex)
        log(f"  round {round_no}: verified {len(batch)} drafts; "
            + ", ".join(f"{s}={len(accepted[s])}" for s in sorted(queues)))
    return [ex for skill in sorted(accepted) for ex in sorted(accepted[skill], key=lambda e: e["id"])]


def _replay(
    batch: Sequence[templates.Draft], lang: Language, workers: int, report: Report,
) -> dict[int, dict[str, oracle.Verdict]]:
    """Replay every candidate of every draft; returns draft id -> keys -> verdict."""
    jobs: list[tuple[int, dict[str, Any], str]] = []
    for draft in batch:
        ex = draft.exercise(lang.name)
        ex["id"] = draft.uid
        jobs.extend((id(draft), ex, k) for k in candidate_keys(draft, ex))
    report.replays += len(jobs)
    chunks = [jobs[i:i + JOBS_PER_PROCESS] for i in range(0, len(jobs), JOBS_PER_PROCESS)]
    runner = oracle.subprocess_runner(timeout_s=JOB_TIMEOUT_S)
    out: dict[int, dict[str, oracle.Verdict]] = collections.defaultdict(dict)
    def run(chunk):
        return oracle.verify_many([(e, k) for _, e, k in chunk], runner)

    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        for chunk, verdicts in zip(chunks, pool.map(run, chunks)):
            for (key, _, keys), verdict in zip(chunk, verdicts, strict=True):
                out[key][keys] = verdict
                if verdict.outcome is not None and verdict.outcome.mode == "timeout":
                    report.rejections[("timeout-job", "-", keys)] += 1
    return out


def _probe(batch: Sequence[templates.Draft], lang: Language, workers: int) -> dict[int, list[list[int] | None]]:
    """Land every ``gates.cursor_probes`` motion of each cursor draft; draft id -> landings."""
    jobs = []
    for draft in batch:
        if draft.kind != oracle.Kind.CURSOR:
            continue
        ex = draft.exercise(lang.name)
        jobs.append((id(draft), ex, [k for k, _ in gates.cursor_probes(ex)]))
    chunks = [jobs[i:i + PROBE_JOBS_PER_PROCESS] for i in range(0, len(jobs), PROBE_JOBS_PER_PROCESS)]

    def run(chunk):
        return oracle.probe_cursors([(ex, keys) for _, ex, keys in chunk], timeout_s=JOB_TIMEOUT_S)

    out: dict[int, list[list[int] | None]] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
        for chunk, landed in zip(chunks, pool.map(run, chunks)):
            for (key, _, _), result in zip(chunk, landed, strict=True):
                out[key] = result
    return out


def _write(
    out: pathlib.Path, exercises: list[dict[str, Any]], report: Report,
    used_sources: list[tuple[sources.Source, str, str]], frequencies: dict[str, Any], stamp: str,
):
    if out.exists():
        shutil.rmtree(out)
    (out / "stats").mkdir(parents=True)
    index: dict[str, Any] = {"version": 1, "generated": datetime.date.today().isoformat(), "verified": stamp, "langs": {}}
    for ex in exercises:
        lang_dir = out / "exercises" / ex["lang"] / ex["skill"]
        lang_dir.mkdir(parents=True, exist_ok=True)
        (lang_dir / f"{ex['id'].rsplit('/', 1)[1]}.json").write_text(json.dumps(ex, indent=2) + "\n")
    for lang, skills in report.counts.items():
        entry = index["langs"].setdefault(lang, {"skills": {}})
        for skill in skills:
            mine = [e for e in exercises if e["lang"] == lang and e["skill"] == skill]
            entry["skills"][skill] = {
                "ids": [e["id"] for e in mine], "count": len(mine),
                "parMedian": statistics.median(e["par"]["count"] for e in mine) if mine else None,
                "thin": gates.is_thin(len(mine)),
                "templates": dict(collections.Counter(e["template"] for e in mine)),
                "kinds": dict(collections.Counter(e["kind"] for e in mine)),
                "reviewed": sum(e.get("reviewed", False) for e in mine),
            }
    (out / "index.json").write_text(json.dumps(index, indent=2) + "\n")
    (out / "stats" / "node_frequency.json").write_text(json.dumps(frequencies, indent=2) + "\n")
    (out / "stats" / "gates.json").write_text(json.dumps(_gate_stats(report), indent=2) + "\n")
    (out / "ATTRIBUTION.md").write_text(_attribution(exercises, used_sources))
    (out / "supported_commands.md").write_text(_supported_commands(exercises, stamp))


def _gate_stats(report: Report) -> dict[str, Any]:
    by_gate: dict[str, dict[str, int]] = collections.defaultdict(dict)
    for (gate, skill, template), n in sorted(report.rejections.items()):
        by_gate[gate][f"{skill}/{template}"] = n
    return {
        "windows": report.windows, "drafts": report.drafts, "replays": report.replays,
        "accepted": report.counts, "thin": report.thin(),
        "rejected": {g: {"total": sum(v.values()), "by": v} for g, v in by_gate.items()},
    }


def _attribution(exercises: Iterable[dict[str, Any]], used: list[tuple[sources.Source, str, str]]) -> str:
    per_path = collections.Counter((e["source"]["repo"], e["source"]["path"]) for e in exercises)
    parts = [
        "# Attribution\n",
        "Exercise snippets are cut from the source files below, at the pinned commit, under",
        "the licence shown. Snippets are windowed and dedented, and multi-line docstrings are",
        "cut to their summary line; the code is otherwise unchanged",
        "except for the edit each exercise asks for. Generated by `vimtrainer-content build`.\n",
    ]
    for src, copyright_line, license_text in used:
        files = sorted((p, n) for (repo, p), n in per_path.items() if repo == src.repo)
        parts += [
            f"## {src.repo}\n",
            f"- URL: {src.url}",
            f"- Commit: `{src.commit or 'local'}`",
            f"- Licence: {src.license} ({copyright_line})",
            f"- Files used: {len(files)}, exercises: {sum(n for _, n in files)}\n",
            "| path | exercises |", "|---|---|",
            *(f"| `{p}` | {n} |" for p, n in files),
            "\n<details><summary>Licence text</summary>\n", "```", license_text.strip(), "```", "</details>\n",
        ]
    return "\n".join(parts) + "\n"


def _supported_commands(exercises: Sequence[dict[str, Any]], stamp: str) -> str:
    rows: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for ex in exercises:
        rows[ex["skill"]][_shape(ex)] += 1
    lines = [
        "# Supported commands\n",
        f"Command shapes used by canonical solutions, verified in {stamp}.",
        "Inserted text is shown as `{text}`, counts as `N`.",
        "Browser (codemirror-vim) verification: `make content` replays every par in the app's editor",
        "and records `emulator.web` per exercise (see stats/emulator_web.json).",
        "VSCodeVim and IdeaVim verification is not done yet: TODO(mvp).\n",
        "| skill | command shape | exercises |", "|---|---|---|",
    ]
    for skill in sorted(rows):
        for shape, n in rows[skill].most_common():
            lines.append(f"| {skill} | `{shape}` | {n} |")
    return "\n".join(lines) + "\n"


def _shape(ex: dict[str, Any]) -> str:
    keys = ex["par"]["keys"]
    for name in ("text", "new", "old"):
        value = ex.get("params", {}).get(name)
        if isinstance(value, str) and value and value in keys:
            keys = keys.replace(value, "{" + name + "}")
    shape = "".join("N" if t.isdigit() else t for t in oracle.tokenize_keys(keys))
    while "NN" in shape:
        shape = shape.replace("NN", "N")
    return shape.replace("|", "\\|")
